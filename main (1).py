def count_moods(data):
    happy = 0
    sad = 0
    for sentence, mood in data:
        if mood == "Happy":
            happy += 1   # add 1 to happy
        else:
            sad += 1   # add 1 to sad
    return happy, sad

happy_words = ["won", "surprise", "excited"]
sad_words = ["lost", "failed", "upset"]

def clean(sentence):
    sentence = sentence.lower()
    for ch in "!?.,;:'\"":
        sentence = sentence.replace(ch, "")
    return sentence.split()

def guess_mood(sentence):
    words = clean(sentence)
    happy_score = 0
    sad_score = 0
    for w in words:
        if w in happy_words:
            happy_score += 1   # add 1 to happy_score
        if w in sad_words:
            sad_score += 1  # add 1 to sad_score
    if happy_score > sad_score:
        return "Happy"
    elif sad_score > happy_score:
        return "Sad"
    else:
        return "Sad"   # tie: choose "Happy" or "Sad"

print(count_moods(train_data))

